// Computes the sha256 of every inline script and inline style in the site's HTML pages and writes
// them to src/csp-hashes.js, which src/csp.js puts in the Content-Security-Policy header
// (security audit 2026-11-05, F14, F15 and D1: no 'unsafe-inline' for scripts).
//   node build-csp-hashes.mjs           rewrite src/csp-hashes.js
//   node build-csp-hashes.mjs --check   exit 1 when src/csp-hashes.js is out of date
// Run it again whenever an inline <script> or <style> changes (inline-page-styles.mjs does that for
// the two pages whose stylesheets are inlined); check-pages.mjs fails the build when it is stale.
// A browser hashes the text the HTML parser builds, which turns CRLF into LF: so does this.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const OUTPUT = fileURLToPath(new URL('./src/csp-hashes.js', import.meta.url));
// Folders that are never served (.assetsignore) or hold no site pages.
const SKIP = new Set(['node_modules', '.git', 'output', 'tmp', 'Microsoft', '.claude', 'deploy', 'neuroncli/auth-server', 'anti-slop']);
// <script> types the browser runs (or applies) and so checks against script-src. Data blocks
// (application/ld+json) are never executed and are not checked.
const SCRIPT_TYPES = new Set(['', 'text/javascript', 'application/javascript', 'module', 'importmap', 'speculationrules']);
const BACKSLASH = String.fromCharCode(92);
const slashes = path => path.split(BACKSLASH).join('/');

export const hashOf = text => 'sha256-' + createHash('sha256').update(text.replace(/\r\n?/g, '\n'), 'utf8').digest('base64');

function* htmlFiles(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    const rel = slashes(relative(root, path));
    if (SKIP.has(name) || SKIP.has(rel)) continue;
    if (statSync(path).isDirectory()) yield* htmlFiles(path);
    else if (name.endsWith('.html')) yield rel;
  }
}

const attributeOf = (attributes, name) =>
  new RegExp('\\b' + name + '\\s*=\\s*(?:"([^"]*)"|\'([^\']*)\'|([^\\s>]+))', 'i').exec(attributes);

export function collectInlineHashes(base = root) {
  const scripts = new Map();
  const styles = new Map();
  const add = (map, hash, file) => map.set(hash, [...(map.get(hash) || []), file]);
  for (const file of htmlFiles(base)) {
    const html = readFileSync(join(base, file), 'utf8');
    for (const [, attributes, text] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
      if (attributeOf(attributes, 'src')) continue;
      const type = (attributeOf(attributes, 'type')?.slice(1).find(Boolean) || '').trim().toLowerCase();
      if (!SCRIPT_TYPES.has(type) || !text.trim()) continue;
      add(scripts, hashOf(text), file);
    }
    for (const [, , text] of html.matchAll(/<style\b([^>]*)>([\s\S]*?)<\/style>/gi)) {
      if (text.trim()) add(styles, hashOf(text), file);
    }
  }
  return { scripts, styles };
}

export function render({ scripts, styles }) {
  const list = map => [...map.keys()].sort().map(hash => `  '${hash}',`).join('\n');
  return `// Generated by build-csp-hashes.mjs: do not edit. sha256 of every inline <script> and <style> in the
// site's HTML pages (security audit 2026-11-05, F14, F15, D1), which src/csp.js allows in place of
// 'unsafe-inline'. Run \`node build-csp-hashes.mjs\` after changing an inline script or style.
export const INLINE_SCRIPT_HASHES = Object.freeze([
${list(scripts)}
]);
export const INLINE_STYLE_HASHES = Object.freeze([
${list(styles)}
]);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1].split(BACKSLASH).join(BACKSLASH)) {
  const next = render(collectInlineHashes());
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUTPUT, 'utf8'); } catch { /* missing */ }
    if (current.replace(/\r\n/g, '\n') !== next) {
      console.error('src/csp-hashes.js is out of date: run `node build-csp-hashes.mjs`');
      process.exit(1);
    }
    console.log('src/csp-hashes.js is current');
  } else {
    writeFileSync(OUTPUT, next);
    console.log('wrote src/csp-hashes.js');
  }
}
