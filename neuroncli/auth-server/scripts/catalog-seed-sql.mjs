#!/usr/bin/env node
// Generates migrations/20261029000700_catalog_seed.sql from the code catalog (src/catalog.js
// CATALOG plus src/catalog-claude.js), so the seeded rows equal code exactly. check-catalog-db.mjs
// fails when the committed file differs from what this prints, or when a seeded row differs from
// its code spec.
//
//   node scripts/catalog-seed-sql.mjs            # writes the migration
//   node scripts/catalog-seed-sql.mjs --stdout   # prints it
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { codeCatalog } from '../src/catalog-db.js';
import { ANTHROPIC_PAID_OFFER } from '../src/catalog-claude.js';
import { canonicalJson } from '../src/oiop/manifest.js';

export const SEED_FILE = fileURLToPath(new URL('../migrations/20261029000700_catalog_seed.sql', import.meta.url));

const literal = value => (value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);
const json = value => `${literal(canonicalJson(value))}::jsonb`;

export function seedSql() {
  const items = codeCatalog().items;
  const offer = ANTHROPIC_PAID_OFFER;
  const rows = items.map((item, index) => `  (${index + 1}, ${literal(item.id)}, ${json(item.spec)})`).join(',\n');
  return `BEGIN;

-- Seed of the data-driven catalog (migration 20261029000600_catalog_models.sql). GENERATED by
-- scripts/catalog-seed-sql.mjs from the code catalog (src/catalog.js CATALOG and
-- src/catalog-claude.js); do not edit by hand. check-catalog-db.mjs proves every seeded row equals
-- its code spec, so the rows serve exactly what code review approved.
--
-- 1. The anthropic.paid OIOP offer behind the Claude pools (src/catalog-claude.js
--    ANTHROPIC_PAID_OFFER, also in src/oiop/offers.js BUILTIN_OFFERS). ON CONFLICT DO NOTHING: if
--    another migration created it first, that row stays.
-- 2. ${items.length} active models: the ${items.length - 2} code models and Claude Sonnet 5.5 / Opus 5.5, revision 1
--    approved by 'migration', one 'seed' audit row each.
-- 3. Discovery candidates promoted into gateway_provider_models before this catalog existed become
--    drafts (source 'discovery', revision 1 pending, the provider's default free limits). They were
--    never served (CATALOG_DB_MODELS was off in production) and drafts are not served either.

INSERT INTO public.zerox_offers (id, provider, name, homepage, logo_url, base_url, protocol, access_kind, owner,
  trust_tier, redistribution, trains_on_inputs, commercial_use, expires_after_days, terms_url, terms_sha256,
  prerequisites, limits, evidence, lifecycle, verified_by, verified_at, notes)
VALUES (${literal(offer.id)}, ${literal(offer.provider)}, ${literal(offer.name)}, ${literal(offer.homepage)},
  ${literal(offer.logo_url)}, ${literal(offer.base_url)}, ${literal(offer.protocol)}, ${literal(offer.access_kind)},
  ${literal(offer.owner)}, ${literal(offer.trust_tier)}, ${literal(offer.redistribution)}, ${literal(offer.trains_on_inputs)},
  ${literal(offer.commercial_use)}, ${offer.expires_after_days ?? 'NULL'}, ${literal(offer.terms_url)}, ${literal(offer.terms_sha256)},
  ${json(offer.prerequisites)}, ${json(offer.limits)},
  ${json(offer.evidence)},
  ${literal(offer.lifecycle)}, ${literal(offer.verified_by)}, now(), ${literal(offer.notes)})
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.zerox_offer_events (offer_id, actor, action, to_state, note)
SELECT 'anthropic.paid', 'migration', 'create', 'active',
  'Claude API (paid) for the Claude catalog rows; redistribution permitted by operator decision (2026-10-24)'
WHERE NOT EXISTS (SELECT 1 FROM public.zerox_offer_events AS e WHERE e.offer_id = 'anthropic.paid');

SELECT public.zerox_catalog_context('migration', 'seed',
  'Seeded from the code catalog (src/catalog.js, src/catalog-claude.js); equal to code (check-catalog-db.mjs)');

CREATE TEMP TABLE zerox_catalog_seed (ord integer PRIMARY KEY, id text NOT NULL UNIQUE, spec jsonb NOT NULL) ON COMMIT DROP;

INSERT INTO pg_temp.zerox_catalog_seed (ord, id, spec) VALUES
${rows};

INSERT INTO public.zerox_catalog_models (id, provider_type, status, source)
SELECT s.id, s.spec ->> 'provider_type', 'draft', 'seed' FROM pg_temp.zerox_catalog_seed AS s ORDER BY s.ord;

SELECT public.zerox_catalog_insert_revision(s.id, s.spec, 'migration', 'Code catalog at the time of the data-driven catalog')
FROM pg_temp.zerox_catalog_seed AS s ORDER BY s.ord;

UPDATE public.zerox_catalog_revisions AS r SET approved_by = 'migration', approved_at = now()
FROM pg_temp.zerox_catalog_seed AS s WHERE r.model_id = s.id AND r.revision = 1;

UPDATE public.zerox_catalog_models AS m SET active_revision_id = r.id, status = 'active'
FROM public.zerox_catalog_revisions AS r, pg_temp.zerox_catalog_seed AS s
WHERE s.id = m.id AND r.model_id = m.id AND r.revision = 1;

SELECT public.zerox_catalog_context('migration', 'import',
  'Promoted discovery candidate imported from gateway_provider_models; never served before. A draft until approved on /admin/models.');

INSERT INTO public.zerox_catalog_models (id, provider_type, status, source, candidate_id)
SELECT g.public_model_id, g.provider_id, 'draft', 'discovery', g.candidate_id
FROM public.gateway_provider_models AS g
WHERE g.candidate_id IS NOT NULL AND g.provider_id IN ('openrouter', 'nvidia')
  AND public.zerox_catalog_upstream_ok(g.provider_id, g.provider_model_id)
  AND g.public_model_id = public.zerox_catalog_public_id(g.provider_id, g.provider_model_id)
  AND g.context_window BETWEEN 1024 AND 10000000
  AND NOT EXISTS (SELECT 1 FROM public.zerox_catalog_models AS m WHERE m.id = g.public_model_id)
ON CONFLICT DO NOTHING;

SELECT public.zerox_catalog_insert_revision(m.id, jsonb_build_object(
    'provider_type', m.provider_type, 'upstream_model', g.provider_model_id,
    'display_name', coalesce(nullif(left(btrim(regexp_replace(coalesce(g.display_name, ''), '[[:cntrl:]<>]', '', 'g')), 120), ''), left(m.id, 120)),
    'context_window', g.context_window, 'max_output_tokens', greatest(256, least(g.max_output_tokens, g.context_window, 1000000)),
    'supports_tools', true, 'supports_vision', coalesce(g.supports_vision, false),
    'reasoning_efforts', '[]'::jsonb, 'reasoning_effort_map', '{}'::jsonb, 'aliases', '[]'::jsonb, 'geo_block_free', '[]'::jsonb,
    'auto_rank', NULL, 'position', 1000, 'default_enabled', true,
    'pools', jsonb_build_array(jsonb_build_object('tier', 'free', 'key_slot', m.provider_type || '.free', 'price', NULL,
      'limits', CASE m.provider_type WHEN 'nvidia' THEN '{"rpm": 40, "rpd": 10000, "tpm": null, "tpd": null}'::jsonb
        ELSE '{"rpm": 20, "rpd": 50, "tpm": null, "tpd": null}'::jsonb END,
      'daily_spend_cap_microusd', NULL))),
  'migration', 'Imported from gateway_provider_models')
FROM public.zerox_catalog_models AS m
JOIN public.gateway_provider_models AS g ON g.public_model_id = m.id
WHERE m.source = 'discovery' AND m.status = 'draft'
  AND NOT EXISTS (SELECT 1 FROM public.zerox_catalog_revisions AS r WHERE r.model_id = m.id);

UPDATE public.zerox_catalog_models AS m SET pending_revision_id = r.id
FROM public.zerox_catalog_revisions AS r
WHERE r.model_id = m.id AND r.revision = 1 AND m.source = 'discovery' AND m.status = 'draft' AND m.pending_revision_id IS NULL;

NOTIFY pgrst, 'reload schema';

COMMIT;
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const sql = seedSql();
  if (process.argv.includes('--stdout')) process.stdout.write(sql);
  else {
    writeFileSync(SEED_FILE, sql);
    console.log(`wrote ${SEED_FILE}`);
  }
}
