#!/usr/bin/env node
// Generates migrations/20261029000700_catalog_seed.sql from the code catalog (src/catalog.js
// CATALOG plus src/catalog-claude.js), so the seeded rows equal code exactly. check-catalog-db.mjs
// fails when the committed file differs from what this prints, or when a seeded row differs from
// its code spec.
//
// It also generates migrations/20261106000700_haiku_catalog.sql, the row of Claude Haiku 5.5 (a
// sponsored free pool, docs/PLATFORM_CONTRACT.md section 19) that joined the code catalog after the
// seed was applied in production: the seed file stays exactly what ran there, and the later model
// arrives in its own migration (LATER_MODELS).
//
//   node scripts/catalog-seed-sql.mjs            # writes both migrations
//   node scripts/catalog-seed-sql.mjs --stdout   # prints the seed
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { codeCatalog } from '../src/catalog-db.js';
import { ANTHROPIC_PAID_OFFER } from '../src/catalog-claude.js';
import { canonicalJson } from '../src/oiop/manifest.js';

export const SEED_FILE = fileURLToPath(new URL('../migrations/20261029000700_catalog_seed.sql', import.meta.url));
export const HAIKU_FILE = fileURLToPath(new URL('../migrations/20261106000700_haiku_catalog.sql', import.meta.url));
// Code models that have their own migration after the seed (each one is seeded there, not here).
export const LATER_MODELS = Object.freeze(['anthropic/claude-haiku-5-5']);

const literal = value => (value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);
const json = value => `${literal(canonicalJson(value))}::jsonb`;

export function seedSql() {
  const items = codeCatalog().items.filter(item => !LATER_MODELS.includes(item.id));
  const offer = ANTHROPIC_PAID_OFFER;
  const rows = items.map((item, index) => `  (${index + 1}, ${literal(item.id)}, ${json(item.spec)})`).join(',\n');
  return `BEGIN;

-- Seed of the data-driven catalog (migration 20261029000600_catalog_models.sql). GENERATED by
-- scripts/catalog-seed-sql.mjs from the code catalog (src/catalog.js CATALOG and
-- src/catalog-claude.js); do not edit by hand. check-catalog-db.mjs proves every seeded row equals
-- its code spec, so the rows serve exactly what code review approved.
--
-- 1. The anthropic.paid OIOP offer behind the Claude pools (src/catalog-claude.js
--    ANTHROPIC_PAID_OFFER, also in src/oiop/offers.js BUILTIN_OFFERS). ON CONFLICT DO NOTHING: if
--    another migration created it first, that row stays.
-- 2. ${items.length} active models: the ${items.length - 2} code models and Claude Sonnet 5.5 / Opus 5.5, revision 1
--    approved by 'migration', one 'seed' audit row each.
-- 3. Discovery candidates promoted into gateway_provider_models before this catalog existed become
--    drafts (source 'discovery', revision 1 pending, the provider's default free limits). They were
--    never served (CATALOG_DB_MODELS was off in production) and drafts are not served either.

INSERT INTO public.zerox_offers (id, provider, name, homepage, logo_url, base_url, protocol, access_kind, owner,
  trust_tier, redistribution, trains_on_inputs, commercial_use, expires_after_days, terms_url, terms_sha256,
  prerequisites, limits, evidence, lifecycle, verified_by, verified_at, notes)
VALUES (${literal(offer.id)}, ${literal(offer.provider)}, ${literal(offer.name)}, ${literal(offer.homepage)},
  ${literal(offer.logo_url)}, ${literal(offer.base_url)}, ${literal(offer.protocol)}, ${literal(offer.access_kind)},
  ${literal(offer.owner)}, ${literal(offer.trust_tier)}, ${literal(offer.redistribution)}, ${literal(offer.trains_on_inputs)},
  ${literal(offer.commercial_use)}, ${offer.expires_after_days ?? 'NULL'}, ${literal(offer.terms_url)}, ${literal(offer.terms_sha256)},
  ${json(offer.prerequisites)}, ${json(offer.limits)},
  ${json(offer.evidence)},
  ${literal(offer.lifecycle)}, ${literal(offer.verified_by)}, now(), ${literal(offer.notes)})
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.zerox_offer_events (offer_id, actor, action, to_state, note)
SELECT 'anthropic.paid', 'migration', 'create', 'active',
  'Claude API (paid) for the Claude catalog rows; redistribution permitted by operator decision (2026-10-24)'
WHERE NOT EXISTS (SELECT 1 FROM public.zerox_offer_events AS e WHERE e.offer_id = 'anthropic.paid');

SELECT public.zerox_catalog_context('migration', 'seed',
  'Seeded from the code catalog (src/catalog.js, src/catalog-claude.js); equal to code (check-catalog-db.mjs)');

CREATE TEMP TABLE zerox_catalog_seed (ord integer PRIMARY KEY, id text NOT NULL UNIQUE, spec jsonb NOT NULL) ON COMMIT DROP;

INSERT INTO pg_temp.zerox_catalog_seed (ord, id, spec) VALUES
${rows};

INSERT INTO public.zerox_catalog_models (id, provider_type, status, source)
SELECT s.id, s.spec ->> 'provider_type', 'draft', 'seed' FROM pg_temp.zerox_catalog_seed AS s ORDER BY s.ord;

SELECT public.zerox_catalog_insert_revision(s.id, s.spec, 'migration', 'Code catalog at the time of the data-driven catalog')
FROM pg_temp.zerox_catalog_seed AS s ORDER BY s.ord;

UPDATE public.zerox_catalog_revisions AS r SET approved_by = 'migration', approved_at = now()
FROM pg_temp.zerox_catalog_seed AS s WHERE r.model_id = s.id AND r.revision = 1;

UPDATE public.zerox_catalog_models AS m SET active_revision_id = r.id, status = 'active'
FROM public.zerox_catalog_revisions AS r, pg_temp.zerox_catalog_seed AS s
WHERE s.id = m.id AND r.model_id = m.id AND r.revision = 1;

SELECT public.zerox_catalog_context('migration', 'import',
  'Promoted discovery candidate imported from gateway_provider_models; never served before. A draft until approved on /admin/models.');

INSERT INTO public.zerox_catalog_models (id, provider_type, status, source, candidate_id)
SELECT g.public_model_id, g.provider_id, 'draft', 'discovery', g.candidate_id
FROM public.gateway_provider_models AS g
WHERE g.candidate_id IS NOT NULL AND g.provider_id IN ('openrouter', 'nvidia')
  AND public.zerox_catalog_upstream_ok(g.provider_id, g.provider_model_id)
  AND g.public_model_id = public.zerox_catalog_public_id(g.provider_id, g.provider_model_id)
  AND g.context_window BETWEEN 1024 AND 10000000
  AND NOT EXISTS (SELECT 1 FROM public.zerox_catalog_models AS m WHERE m.id = g.public_model_id)
ON CONFLICT DO NOTHING;

SELECT public.zerox_catalog_insert_revision(m.id, jsonb_build_object(
    'provider_type', m.provider_type, 'upstream_model', g.provider_model_id,
    'display_name', coalesce(nullif(left(btrim(regexp_replace(coalesce(g.display_name, ''), '[[:cntrl:]<>]', '', 'g')), 120), ''), left(m.id, 120)),
    'context_window', g.context_window, 'max_output_tokens', greatest(256, least(g.max_output_tokens, g.context_window, 1000000)),
    'supports_tools', true, 'supports_vision', coalesce(g.supports_vision, false),
    'reasoning_efforts', '[]'::jsonb, 'reasoning_effort_map', '{}'::jsonb, 'aliases', '[]'::jsonb, 'geo_block_free', '[]'::jsonb,
    'auto_rank', NULL, 'position', 1000, 'default_enabled', true,
    'pools', jsonb_build_array(jsonb_build_object('tier', 'free', 'key_slot', m.provider_type || '.free', 'price', NULL,
      'limits', CASE m.provider_type WHEN 'nvidia' THEN '{"rpm": 40, "rpd": 10000, "tpm": null, "tpd": null}'::jsonb
        ELSE '{"rpm": 20, "rpd": 50, "tpm": null, "tpd": null}'::jsonb END,
      'daily_spend_cap_microusd', NULL))),
  'migration', 'Imported from gateway_provider_models')
FROM public.zerox_catalog_models AS m
JOIN public.gateway_provider_models AS g ON g.public_model_id = m.id
WHERE m.source = 'discovery' AND m.status = 'draft'
  AND NOT EXISTS (SELECT 1 FROM public.zerox_catalog_revisions AS r WHERE r.model_id = m.id);

UPDATE public.zerox_catalog_models AS m SET pending_revision_id = r.id
FROM public.zerox_catalog_revisions AS r
WHERE r.model_id = m.id AND r.revision = 1 AND m.source = 'discovery' AND m.status = 'draft' AND m.pending_revision_id IS NULL;

NOTIFY pgrst, 'reload schema';

COMMIT;
`;
}

// The Claude Haiku 5.5 catalog migration (see the header of the generated file).
export function haikuSql() {
  const item = codeCatalog().items.find(candidate => candidate.id === 'anthropic/claude-haiku-5-5');
  if (!item) throw new Error('Claude Haiku 5.5 is not in the code catalog');
  return `BEGIN;
-- A few statements and one constraint swap on small tables; give up (and re-run) rather than queue
-- behind a long transaction.
SET LOCAL lock_timeout = '5s';

-- Claude Haiku 5.5 as a sponsored free model on every plan (docs/PLATFORM_CONTRACT.md section 19).
-- GENERATED by scripts/catalog-seed-sql.mjs from the code catalog (src/catalog-claude.js); do not
-- edit by hand. check-catalog-db.mjs proves the row equals its code spec.
--
-- 1. zerox_catalog_slot_ok (the SQL mirror of src/catalog-types.js slotAllowed) accepts the free
--    tier on anthropic.paid, and zerox_catalog_slot_sponsors names the slots whose free pools are
--    sponsored: the operator pays for them, so such a pool may carry a price and a daily spend cap.
-- 2. The table check that kept every free pool unpriced and uncapped now makes that exception for
--    sponsored slots only (zerox_catalog_revision_pools_free_terms). Every other free pool still
--    has no price, cache rates or spend cap.
-- 3. The model row anthropic/claude-haiku-5-5, revision 1 approved by 'migration', one 'seed' audit
--    row. A row the operator created first (any revision) is left as it is. The pool serves only
--    once a gateway that knows sponsored pools is deployed: an older gateway's guardrails drop it
--    as free_pool_priced, and there is no code entry for it there, so it is simply not served.
-- Safe to re-run. Roll back with migrations/down/20261106000700_haiku_catalog.sql.

CREATE OR REPLACE FUNCTION public.zerox_catalog_slot_ok(p_type text, p_tier text, p_slot text)
RETURNS boolean
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT coalesce((p_type, p_tier, p_slot) IN (
    ('gemini', 'free', 'gemini.free'), ('gemini', 'paid', 'gemini.paid'),
    ('groq', 'free', 'groq.free'), ('groq', 'paid', 'groq.paid'),
    ('nvidia', 'free', 'nvidia.free'),
    ('openrouter', 'free', 'openrouter.free'),
    ('omniroute', 'free', 'omniroute.free'),
    ('cloudflare', 'free', 'cloudflare.binding'), ('cloudflare', 'paid', 'cloudflare.binding'),
    ('anthropic', 'free', 'anthropic.paid'), ('anthropic', 'paid', 'anthropic.paid'),
    ('zai', 'free', 'zai.free')
  ), false);
$$;

-- Slots the operator pays for (catalog-types.js KEY_SLOTS \`sponsors\`).
CREATE OR REPLACE FUNCTION public.zerox_catalog_slot_sponsors(p_slot text)
RETURNS boolean
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT coalesce(p_slot IN ('anthropic.paid'), false);
$$;

REVOKE ALL ON FUNCTION public.zerox_catalog_slot_sponsors(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.zerox_catalog_slot_sponsors(text) TO service_role;

DO $$
DECLARE
  v_name text;
BEGIN
  -- The original check is unnamed: find it by what it says (a free pool has no price, cache rates or cap).
  FOR v_name IN SELECT c.conname FROM pg_constraint AS c
    WHERE c.conrelid = 'public.zerox_catalog_revision_pools'::regclass AND c.contype = 'c'
      AND c.conname <> 'zerox_catalog_revision_pools_free_terms'
      AND pg_get_constraintdef(c.oid) LIKE '%cache_write_1h_microusd_per_mtok IS NULL%' LOOP
    EXECUTE format('ALTER TABLE public.zerox_catalog_revision_pools DROP CONSTRAINT %I', v_name);
  END LOOP;
END;
$$;
ALTER TABLE public.zerox_catalog_revision_pools DROP CONSTRAINT IF EXISTS zerox_catalog_revision_pools_free_terms;
ALTER TABLE public.zerox_catalog_revision_pools ADD CONSTRAINT zerox_catalog_revision_pools_free_terms CHECK (
  tier = 'paid' OR public.zerox_catalog_slot_sponsors(key_slot)
  OR (input_microusd_per_mtok IS NULL AND output_microusd_per_mtok IS NULL
    AND cache_read_microusd_per_mtok IS NULL AND cache_write_microusd_per_mtok IS NULL
    AND cache_write_1h_microusd_per_mtok IS NULL AND long_context_threshold IS NULL AND daily_spend_cap_microusd IS NULL));

SELECT public.zerox_catalog_context('migration', 'seed',
  'Claude Haiku 5.5, a sponsored free model on every plan; equal to the code catalog (check-catalog-db.mjs)');

CREATE TEMP TABLE zerox_catalog_haiku (id text PRIMARY KEY, spec jsonb NOT NULL) ON COMMIT DROP;
INSERT INTO pg_temp.zerox_catalog_haiku (id, spec) VALUES
  (${literal(item.id)}, ${json(item.spec)});

INSERT INTO public.zerox_catalog_models (id, provider_type, status, source)
SELECT s.id, s.spec ->> 'provider_type', 'draft', 'seed' FROM pg_temp.zerox_catalog_haiku AS s
WHERE NOT EXISTS (SELECT 1 FROM public.zerox_catalog_models AS m WHERE m.id = s.id);

SELECT public.zerox_catalog_insert_revision(s.id, s.spec, 'migration', 'Claude Haiku 5.5 as a sponsored free model on every plan')
FROM pg_temp.zerox_catalog_haiku AS s
WHERE NOT EXISTS (SELECT 1 FROM public.zerox_catalog_revisions AS r WHERE r.model_id = s.id);

UPDATE public.zerox_catalog_revisions AS r SET approved_by = 'migration', approved_at = now()
FROM pg_temp.zerox_catalog_haiku AS s
WHERE r.model_id = s.id AND r.revision = 1 AND r.approved_at IS NULL AND r.rejected_at IS NULL
  AND EXISTS (SELECT 1 FROM public.zerox_catalog_models AS m WHERE m.id = s.id AND m.source = 'seed' AND m.active_revision_id IS NULL);

UPDATE public.zerox_catalog_models AS m SET active_revision_id = r.id, pending_revision_id = NULL, status = 'active'
FROM public.zerox_catalog_revisions AS r, pg_temp.zerox_catalog_haiku AS s
WHERE s.id = m.id AND r.model_id = m.id AND r.revision = 1 AND r.approved_by = 'migration'
  AND m.source = 'seed' AND m.active_revision_id IS NULL;

-- Applied again after its down script (which disables the row; rows are never deleted): enable it.
SELECT public.zerox_catalog_set_status(m.id, 'active', 'migration', 'Claude Haiku 5.5 enabled again by 20261106000700_haiku_catalog.sql')
FROM public.zerox_catalog_models AS m
WHERE m.id IN (SELECT s.id FROM pg_temp.zerox_catalog_haiku AS s) AND m.status = 'disabled' AND m.active_revision_id IS NOT NULL
  AND (SELECT e.note FROM public.zerox_catalog_events AS e WHERE e.model_id = m.id ORDER BY e.id DESC LIMIT 1)
    = 'Claude Haiku 5.5 disabled by the rollback of 20261106000700_haiku_catalog.sql';

NOTIFY pgrst, 'reload schema';

COMMIT;
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--stdout')) process.stdout.write(seedSql());
  else {
    // A file whose text is already current (line endings aside: a Windows checkout has CRLF) is left alone.
    for (const [file, sql] of [[SEED_FILE, seedSql()], [HAIKU_FILE, haikuSql()]]) {
      const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
      if (current === sql) console.log(`up to date ${file}`);
      else { writeFileSync(file, sql); console.log(`wrote ${file}`); }
    }
  }
}
